const UNKNOWN: [u8; 7] = [0b11111; 7];

fn bitmap(c: char) -> [u8; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map(|(_, b)| *b)
        .unwrap_or(UNKNOWN)
}

/// Pixel rectangles `[x, y, w, h]` for each lit cell of `s`, top-left at `(x, y)`.
pub fn layout(s: &str, x: f32, y: f32, scale: f32) -> Vec<[f32; 4]> {
    let mut out = Vec::new();
    for (i, c) in s.chars().enumerate() {
        let gx = x + i as f32 * ADVANCE * scale;
        for (row, bits) in bitmap(c).iter().enumerate() {
            for col in 0..GLYPH_W {
                if bits & (0b10000 >> col) != 0 {
                    out.push([
                        gx + col as f32 * scale,
                        y + row as f32 * scale,
                        scale,
                        scale,
                    ]);
                }
            }
        }
    }
    out
}

/// Width in pixels of `s` at `scale`.
pub fn text_width(s: &str, scale: f32) -> f32 {
    s.chars().count() as f32 * ADVANCE * scale
}

#[cfg(test)]
mod tests {
    use super::*;

    fn glyph(c: char) -> [u8; 7] {
        GLYPHS.iter().find(|(g, _)| *g == c).expect("glyph").1
    }

    #[test]
    fn layout_digit_one() {
        let rects = layout("1", 0.0, 0.0, 1.0);
        let lit: usize = glyph('1').iter().map(|r| r.count_ones() as usize).sum();
        assert_eq!(rects.len(), lit);
        for row in 0..7 {
            for col in 0..5 {
                let on = glyph('1')[row] & (0b10000 >> col) != 0;
                let found = rects
                    .iter()
                    .any(|r| r[0] == col as f32 && r[1] == row as f32);
                assert_eq!(on, found, "cell ({col}, {row})");
            }
        }
        assert!(
            rects
                .iter()
                .all(|r| r[0] < 5.0 && r[1] < 7.0 && r[2] == 1.0 && r[3] == 1.0)
        );
    }

    #[test]
    fn layout_advances() {
        let one = layout("1", 0.0, 0.0, 2.0).len();
        let rects = layout("11", 0.0, 0.0, 2.0);
        assert_eq!(rects.len(), one * 2);
        assert!(rects[one..].iter().all(|r| r[0] >= 12.0));
    }

    #[test]
    fn unknown_char_box() {
        assert_eq!(layout("~", 0.0, 0.0, 1.0).len(), 35);
    }

    #[test]
    fn lowercase_uses_uppercase_shapes() {
        assert_eq!(layout("fps", 0.0, 0.0, 1.0), layout("FPS", 0.0, 0.0, 1.0));
    }
}
